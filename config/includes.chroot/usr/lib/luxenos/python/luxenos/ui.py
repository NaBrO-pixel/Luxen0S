"""GTK 4 bootstrap shared by every LuxenOS desktop application.

Call init() before anything else touches GTK: gtk4-layer-shell has to be
loaded before libwayland-client, so it is pulled in with ctypes first (this is
what upstream documents for Python). If the library is missing, or the
compositor lacks wlr-layer-shell, LAYER_SHELL stays False and callers fall
back to ordinary windows that the Sway config floats and places.

Styling has three layers, lowest priority first:
  1. FALLBACK_PALETTE: the glass.conf defaults, so a missing theme still reads
  2. /usr/share/luxenos/ui/shell.css: layout shared by all LuxenOS apps
  3. ~/.config/luxenos/glass/shell.css: generated by `luxenos-glass apply`
     from glass.conf and the Accessibility controls (colours, radii, sheen,
     shadows, transitions). It is the single source of truth for the look.
"""

import ctypes
import os
import subprocess
import sys

from . import config

LAYER_SHELL = False
Gtk = Gdk = Gio = GLib = LayerShell = None

STATIC_CSS = os.environ.get("LUXENOS_UI_CSS", "/usr/share/luxenos/ui/shell.css")

# Same values luxenos-glass derives from the shipped glass.conf (dark, balanced).
FALLBACK_PALETTE = """
@define-color glass_bg rgba(20,26,38,0.82);
@define-color glass_bg_strong rgba(20,26,38,1.00);
@define-color glass_border rgba(255,255,255,0.26);
@define-color glass_hi rgba(255,255,255,0.09);
@define-color glass_fg #e8edf7;
@define-color glass_fg_dim #94a0b8;
@define-color glass_accent #7aa2ff;
@define-color glass_accent_soft rgba(122,162,255,0.30);
@define-color glass_warn #f0c05a;
@define-color glass_crit #ff6b62;
.lx-glass { border-radius: 12px; }
.lx-card, .lx-tile, .lx-row { border-radius: 8px; }
"""


def init(layer_shell=False):
    """Import GTK (and optionally gtk4-layer-shell). Returns the Gtk module."""
    global LAYER_SHELL, Gtk, Gdk, Gio, GLib, LayerShell
    if Gtk is not None:
        return Gtk
    want_ls = layer_shell and os.environ.get("WAYLAND_DISPLAY") and not os.environ.get("LUXENOS_NO_LAYER_SHELL")
    if want_ls:
        try:
            ctypes.CDLL("libgtk4-layer-shell.so.0")
        except OSError:
            want_ls = False
    import gi
    gi.require_version("Gtk", "4.0")
    gi.require_version("Gdk", "4.0")
    from gi.repository import Gdk as _Gdk, Gio as _Gio, GLib as _GLib, Gtk as _Gtk
    Gtk, Gdk, Gio, GLib = _Gtk, _Gdk, _Gio, _GLib
    if want_ls:
        try:
            gi.require_version("Gtk4LayerShell", "1.0")
            from gi.repository import Gtk4LayerShell as _LS
            LayerShell = _LS
            LAYER_SHELL = bool(_LS.is_supported())
        except (ImportError, ValueError):
            LAYER_SHELL = False
    return Gtk


def generated_css_path():
    return os.path.join(config.luxenos_config_dir(), "glass", "shell.css")


_providers = []


def load_css():
    """Install the LuxenOS stylesheet layers on the default display."""
    display = Gdk.Display.get_default()
    if display is None:
        return
    for p in _providers:
        Gtk.StyleContext.remove_provider_for_display(display, p)
    _providers.clear()
    prio = Gtk.STYLE_PROVIDER_PRIORITY_APPLICATION
    layers = [("data", FALLBACK_PALETTE)]
    if os.path.exists(STATIC_CSS):
        layers.append(("path", STATIC_CSS))
    gen = generated_css_path()
    if not os.path.exists(gen) and shutil_which("luxenos-glass"):
        # First run before the session generated the theme: make it now.
        subprocess.run(["luxenos-glass", "apply", "--files-only"],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=20, check=False)
    if os.path.exists(gen):
        layers.append(("path", gen))
    for i, (kind, value) in enumerate(layers):
        provider = Gtk.CssProvider()
        try:
            if kind == "data":
                provider.load_from_string(value) if hasattr(provider, "load_from_string") \
                    else provider.load_from_data(value, -1)
            else:
                provider.load_from_path(value)
        except GLib.Error as e:
            print("luxenos: stylesheet %s ignored: %s" % (value if kind == "path" else "fallback", e), file=sys.stderr)
            continue
        Gtk.StyleContext.add_provider_for_display(display, provider, prio + i)
        _providers.append(provider)


def watch_theme(callback=None):
    """Reload the stylesheet when luxenos-glass regenerates it."""
    path = generated_css_path()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    monitor = Gio.File.new_for_path(os.path.dirname(path)).monitor_directory(Gio.FileMonitorFlags.NONE, None)

    def changed(_m, f, _o, event):
        if f.get_basename() == "shell.css" and event in (
                Gio.FileMonitorEvent.CHANGES_DONE_HINT, Gio.FileMonitorEvent.CREATED,
                Gio.FileMonitorEvent.RENAMED, Gio.FileMonitorEvent.MOVED_IN):
            load_css()
            if callback:
                callback()

    monitor.connect("changed", changed)
    return monitor


def shutil_which(name):
    from shutil import which
    return which(name)


def reduce_motion():
    return config.reduce_motion()


def transition_ms(default=180):
    return 0 if reduce_motion() else default


# --- layer-shell helpers ------------------------------------------------------

EDGES = ("top", "bottom", "left", "right")


def make_layer(window, namespace, layer="overlay", anchors=(), margins=None,
               keyboard="exclusive", exclusive_zone=None, monitor=None):
    """Turn window into a layer surface. Returns False if unsupported."""
    if not LAYER_SHELL:
        return False
    LS = LayerShell
    if not LS.is_layer_window(window):
        LS.init_for_window(window)
    LS.set_namespace(window, namespace)
    LS.set_layer(window, {"overlay": LS.Layer.OVERLAY, "top": LS.Layer.TOP,
                          "bottom": LS.Layer.BOTTOM}[layer])
    edge_map = {"top": LS.Edge.TOP, "bottom": LS.Edge.BOTTOM, "left": LS.Edge.LEFT, "right": LS.Edge.RIGHT}
    for edge in EDGES:
        LS.set_anchor(window, edge_map[edge], edge in anchors)
    for edge, value in (margins or {}).items():
        LS.set_margin(window, edge_map[edge], int(value))
    LS.set_keyboard_mode(window, {"exclusive": LS.KeyboardMode.EXCLUSIVE,
                                  "on_demand": LS.KeyboardMode.ON_DEMAND,
                                  "none": LS.KeyboardMode.NONE}[keyboard])
    if exclusive_zone == "auto":
        LS.auto_exclusive_zone_enable(window)
    elif exclusive_zone is not None:
        LS.set_exclusive_zone(window, int(exclusive_zone))
    if monitor is not None:
        LS.set_monitor(window, monitor)
    return True


def set_keyboard_mode(window, mode):
    if LAYER_SHELL:
        LayerShell.set_keyboard_mode(window, {"exclusive": LayerShell.KeyboardMode.EXCLUSIVE,
                                              "on_demand": LayerShell.KeyboardMode.ON_DEMAND,
                                              "none": LayerShell.KeyboardMode.NONE}[mode])


# --- small widgets and utilities ---------------------------------------------

def label(text, css=None, xalign=0.0, wrap=False, selectable=False):
    lbl = Gtk.Label(label=text, xalign=xalign)
    if wrap:
        lbl.set_wrap(True)
    if selectable:
        lbl.set_selectable(True)
    for c in (css or "").split():
        lbl.add_css_class(c)
    return lbl


def accessible_label(widget, text):
    """Name a widget for screen readers (icon-only buttons need this)."""
    try:
        widget.update_property([Gtk.AccessibleProperty.LABEL], [text])
    except (AttributeError, TypeError):
        pass
    widget.set_tooltip_text(text)


def icon_button(icon_name, tooltip, callback, css="flat"):
    btn = Gtk.Button.new_from_icon_name(icon_name)
    for c in css.split():
        btn.add_css_class(c)
    accessible_label(btn, tooltip)
    btn.connect("clicked", lambda *_: callback())
    return btn


def add_escape_handler(window, callback):
    ctl = Gtk.EventControllerKey()

    def on_key(_c, keyval, _code, _state):
        if keyval == Gdk.KEY_Escape:
            callback()
            return True
        return False

    ctl.connect("key-pressed", on_key)
    window.add_controller(ctl)


def spawn(argv):
    """Start a program detached from this process (argv list, no shell)."""
    try:
        subprocess.Popen(argv, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                         stderr=subprocess.DEVNULL, start_new_session=True, close_fds=True)
        return True
    except OSError as e:
        print("luxenos: cannot start %s: %s" % (argv[0], e), file=sys.stderr)
        return False


def alert(parent, heading, body="", buttons=("OK",), default=0, cancel=-1, callback=None, destructive=None):
    """Modal message with buttons; callback(index) receives the choice (-1 = dismissed)."""
    dialog = Gtk.AlertDialog()
    dialog.set_message(heading)
    if body:
        dialog.set_detail(body)
    dialog.set_buttons(list(buttons))
    dialog.set_default_button(default)
    dialog.set_cancel_button(cancel if cancel >= 0 else len(buttons) - 1)
    dialog.set_modal(True)

    def done(d, res):
        try:
            idx = d.choose_finish(res)
        except GLib.Error:
            idx = -1
        if callback:
            callback(idx)

    dialog.choose(parent, None, done)
    return dialog


def human_bytes(n):
    n = float(n)
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if abs(n) < 1024 or unit == "TiB":
            return ("%.0f %s" if unit == "B" else "%.1f %s") % (n, unit)
        n /= 1024.0
    return "%.1f TiB" % n


def app_icon_name(name, fallback="application-x-executable"):
    theme = Gtk.IconTheme.get_for_display(Gdk.Display.get_default())
    if name and theme.has_icon(name):
        return name
    if name and theme.has_icon(name.lower()):
        return name.lower()
    return fallback


def gicon_image(gicon, size, fallback="application-x-executable"):
    img = Gtk.Image()
    img.set_pixel_size(size)
    if gicon is not None:
        img.set_from_gicon(gicon)
    else:
        img.set_from_icon_name(fallback)
    return img


def run_app(app_class, argv=None):
    app = app_class()
    return app.run(argv if argv is not None else sys.argv)
